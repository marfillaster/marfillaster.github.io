// Regenerates workers/remix-content.generated.ts — the static import map that
// feeds Platform.content() on workerd (wrangler bundles the .md/.mdx files as
// text modules; workerd has no fs and esbuild has no import glob). Run via
// `pnpm gen:remix-content` after adding/removing a content file; the file is
// committed so the worker build is deterministic.

import { readdir, writeFile } from "node:fs/promises";
import { extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(fileURLToPath(import.meta.url), "../..");
const contentDir = join(repoRoot, "src/content");
const outPath = join(repoRoot, "workers/remix-content.generated.ts");

async function listContentFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        return listContentFiles(path);
      }
      return [".md", ".mdx"].includes(extname(entry.name)) ? [path] : [];
    }),
  );
  return files.flat();
}

const files = (await listContentFiles(contentDir))
  .map((path) => relative(contentDir, path).split(sep).join("/"))
  .sort();

const imports = files
  .map((file, i) => `import c${i} from "../src/content/${file}";`)
  .join("\n");
const entries = files.map((file, i) => `  ["${file}", c${i}],`).join("\n");

const output = `// Generated by scripts/generate-remix-content.mjs — do not edit.
// Static text-module imports for Platform.content() on workerd.
${imports}

export const CONTENT: ReadonlyArray<[string, string]> = [
${entries}
];
`;

await writeFile(outPath, output);
console.log(`wrote ${relative(repoRoot, outPath)} (${files.length} files)`);
