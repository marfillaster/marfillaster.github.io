// Regenerates workers/cache-digests.generated.ts from scripts/lib/cache-digests.mjs.
// The workerd adapter hands the result to the app through Platform.digests, the
// same way remix-content.generated.ts feeds Platform.content().
//
// Runs last in `pnpm cf:build`, after the asset build has rewritten
// app/assets-manifest.generated.ts. The output is committed so the worker
// bundle stays deterministic.

import { writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CACHE_EPOCH } from "../src/lib/cache-epoch.mjs";
import { computeDigests } from "./lib/cache-digests.mjs";

const repoRoot = resolve(fileURLToPath(import.meta.url), "../..");
const outPath = resolve(repoRoot, "workers/cache-digests.generated.ts");

const { build, paths, assets } = await computeDigests(repoRoot, CACHE_EPOCH);

function serialize(record) {
  return Object.keys(record)
    .sort()
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(record[key])},`)
    .join("\n");
}

await writeFile(
  outPath,
  `// Generated by scripts/generate-cache-digests.mjs — do not edit.
// Per-path content digests: document ETags, inner cache keys, and the
// post-deploy reconcile diff all read from here.

/** Digest of the shared code and styles, folded into every path digest. */
export const BUILD_DIGEST = ${JSON.stringify(build)};

/** Rendered document paths → digest of everything that page renders from. */
export const PATH_DIGESTS: Readonly<Record<string, string>> = {
${serialize(paths)}
};

/** Non-fingerprinted public/ files → digest of their bytes. */
export const ASSET_DIGESTS: Readonly<Record<string, string>> = {
${serialize(assets)}
};
`,
);

console.log(
  `wrote ${relative(repoRoot, outPath)} (${Object.keys(paths).length} paths, ${Object.keys(assets).length} assets)`,
);
